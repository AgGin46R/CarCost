package com.aggin.carcost.data.reference

import java.util.Locale

/**
 * Сети АЗС: распознавание в тексте и сведение написаний к одному названию.
 *
 * Список жил внутри сканера чеков, где сверялся с распознанным текстом. Теперь
 * он нужен и второму потребителю — подсчёту цен по заправкам: без сведения
 * написаний «Лукойл», «лукойл на Ленина» и «ЛУКОЙЛ №42» окажутся тремя разными
 * заправками, и сравнивать цены будет не с чем.
 *
 * Названия НЕ переводятся и не лежат в ресурсах. Это имена собственные, которые
 * сверяются с текстом чека и с тем, что человек ввёл в поле «Место». И чек, и
 * ввод остаются русскими независимо от языка интерфейса.
 */
object FuelStations {

    /**
     * Известные сети. Порядок значим: более длинное написание проверяется
     * раньше короткого, иначе «Газпромнефть» свелась бы к «Газпром» — а это
     * разные сети с разными ценами.
     */
    val brands: List<String> = listOf(
        "Газпромнефть", "Газпром",
        "Сургутнефтегаз",
        "Роснефть", "Rosneft",
        "Русснефть", "RusНефть",
        "Лукойл", "LUKOIL",
        "Татнефть",
        "Башнефть",
        "Сибнефть",
        "G-Drive",
        "Neste",
        "Shell",
        "Trassa", "Трасса",
        "Магна",
        "Опти",
        "Лавр",
        "ПТК",
        "ЕКА", "EKA",
        "Феникс",
        "Альфа",
        "Кедр",
        "Sunoco",
        "Total",
        "Eni",
        "BP"
    )

    /**
     * Сеть, упомянутая в строке, либо null.
     *
     * Ищется вхождение без учёта регистра: в поле «Место» пишут как придётся —
     * «лукойл», «Лукойл, ул. Ленина», «АЗС Лукойл №42».
     */
    fun brandIn(text: String): String? {
        if (text.isBlank()) return null
        val upper = text.uppercase(Locale.getDefault())
        return brands.firstOrNull { upper.contains(it.uppercase(Locale.getDefault())) }
    }

    /**
     * Приводит название места к виду, по которому заправки можно объединять.
     *
     * Если сеть узнана — возвращается её название: все точки одной сети попадут
     * в одну строку статистики. Если нет — очищенная строка самого места, с
     * заглавной первой буквой, чтобы «мойка у дома» и «Мойка у дома» не
     * разъехались.
     *
     * @return null для пустого места — такие записи в статистику не попадают:
     *   заправка без названия ничего не говорит о том, где дешевле
     */
    fun normalize(location: String?): String? {
        val raw = location?.trim() ?: return null
        if (raw.isEmpty()) return null
        brandIn(raw)?.let { return it }
        return raw.replaceFirstChar { it.uppercase(Locale.getDefault()) }
    }
}
