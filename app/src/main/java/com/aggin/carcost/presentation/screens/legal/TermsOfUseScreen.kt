/**
 * Пользовательское соглашение.
 *
 * Живёт внутри приложения, а не по ссылке — по той же причине, что и политика
 * конфиденциальности: внешние площадки в России бывают недоступны без обхода
 * блокировок, то есть ровно та аудитория, которой документ адресован, открыть
 * его не может. Внутри приложения он работает всегда и без сети.
 *
 * Дата редакции стоит в одном месте — константе ниже. При правке текста её
 * обязательно менять: соглашение без даты редакции бесполезно, потому что
 * непонятно, с чем именно человек соглашался.
 */
private const val LAST_UPDATED = "20 августа 2026 года"

@OptIn(ExperimentalMaterial3Api::class)
@Composable
fun TermsOfUseScreen(navController: NavController) {
    Scaffold(
        topBar = {
            TopAppBar(
                title = { Text("Пользовательское соглашение") },
                navigationIcon = {
                    IconButton(onClick = { navController.popBackStack() }) {
                        Icon(Icons.AutoMirrored.Filled.ArrowBack, "Назад")
                    }
                },
                colors = TopAppBarDefaults.topAppBarColors(
                    containerColor = MaterialTheme.colorScheme.primaryContainer,
                    titleContentColor = MaterialTheme.colorScheme.onPrimaryContainer
                )
            )
        }
    ) { padding ->
        Column(
            modifier = Modifier
                .fillMaxSize()
                .padding(padding)
                .verticalScroll(rememberScrollState())
                .padding(horizontal = 20.dp, vertical = 16.dp)
        ) {
            Text(
                text = "Дата последнего обновления: $LAST_UPDATED",
                style = MaterialTheme.typography.bodySmall,
                color = MaterialTheme.colorScheme.onSurfaceVariant
            )
            Spacer(Modifier.height(16.dp))

            Text(
                text = "Устанавливая и используя приложение CarCost, вы соглашаетесь " +
                    "с условиями ниже. Если вы с ними не согласны — не пользуйтесь " +
                    "приложением.",
                style = MaterialTheme.typography.bodyMedium
            )

            TERMS_SECTIONS.forEach { (heading, body) ->
                Spacer(Modifier.height(24.dp))
                Text(
                    text = heading,
                    style = MaterialTheme.typography.titleMedium,
                    fontWeight = FontWeight.Bold
                )
                Spacer(Modifier.height(8.dp))
                Text(text = body, style = MaterialTheme.typography.bodyMedium)
            }

            Spacer(Modifier.height(32.dp))
        }
    }
}

