-- Мощность из ПТС. Пустая у всех существующих машин: подставлять сюда
-- справочное значение по модели нельзя — налог человек платит настоящий.
alter table public.cars add column if not exists engine_power_hp integer;

-- Ставка за лошадиную силу. Пусто — считаем по базовой ставке из статьи 361
-- НК. Полной таблицы по регионам здесь нет сознательно: 85 регионов, ставки
-- пересматриваются ежегодно, и устаревшая таблица уверенно называла бы
-- неверную сумму.
alter table public.cars add column if not exists tax_rate_per_hp double precision;
