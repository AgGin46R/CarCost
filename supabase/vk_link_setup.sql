--  Отвязка ВКонтакте от аккаунта
--
--  Привязку делает Edge Function vk-link под service_role, а вот удалить
--  свою связку пользователь может сам — политики достаточно, отдельная
--  функция не нужна.
--
--  Выполнить один раз в Supabase SQL Editor, после vk_identities_setup.sql
-- ════════════════════════════════════════════════════════════

drop policy if exists "vk_identities_self_delete" on public.vk_identities;
create policy "vk_identities_self_delete"
    on public.vk_identities for delete
    using (auth.uid() = user_id);

-- ВАЖНО, чего эта политика НЕ делает:
--
-- Она не мешает отвязаться пользователю, у которого VK — единственный способ
-- входа (аккаунт создан через vk-auth, пароля нет). Такой человек потеряет
-- доступ навсегда. Проверка живёт в приложении: кнопка «Отвязать» не рисуется,
-- если в user_metadata есть vk_id (SupabaseAuthRepository.isVkAccount()).
--
-- Политики на INSERT/UPDATE по-прежнему нет — привязать себе чужой VK
-- напрямую из клиента невозможно, только через vk-link с проверкой токена.
